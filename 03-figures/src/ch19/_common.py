"""Shared helpers for the Chapter 19 figures (prompt 003.1 figure rules; 03-figures/style.md).
Render all: /workspace/books/.venv/bin/python 05-build/tools/render_figures.py ch19
Data: every plotted number is read from the lab's printed output, 04-code/ch19/output/*.txt (regenerated by
04-code/ch19/make_outputs.sh), or recomputed from the lab's seeded simulator 04-code/ch19/sim.py. All of it is the
labeled deterministic stand-in. Figure numbers and captions live in the manuscript, never in the image."""
import sys, inspect, pathlib, re
R = pathlib.Path(__file__).resolve().parents[3]
for p in ("05-build/design", "04-code/fieldkit", "04-code/ch19", "03-figures/src/signatures"):
    sys.path.insert(0, str(R / p))
import fde_style as S  # noqa: E402
S.use()
import matplotlib.pyplot as plt  # noqa: E402,F401
plt.rcParams["legend.framealpha"] = 1.0
plt.rcParams["legend.fancybox"] = False
OUT = R / "04-code/ch19/output"


def text(name):
    return (OUT / f"{name}.txt").read_text()


def dct(s):
    return {k: int(v) for k, v in re.findall(r"'([\w-]+)': (\d+)", s)}


def save(fig, n, kind="plot", data="04-code/ch19 lab output"):
    src = inspect.stack()[1].filename
    return S.save(fig, f"fig19-{n:02d}", kind=kind, source=src, data=data, strict=True)


def blank(ax, xlim=(0, 10), ylim=(0, 6)):
    ax.set_xlim(*xlim); ax.set_ylim(*ylim); ax.axis("off")
